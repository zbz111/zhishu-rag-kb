from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

OUT = Path(__file__).resolve().parent.parent / "data" / "test_docs"
FONT = "C:/Windows/Fonts/simhei.ttf"
FONT_NAME = "Hei"

pdfmetrics.registerFont(TTFont(FONT_NAME, FONT))
_STYLES = getSampleStyleSheet()
S_TITLE = ParagraphStyle("t", parent=_STYLES["Title"], fontName=FONT_NAME, fontSize=19, leading=26, spaceAfter=14)
S_H1 = ParagraphStyle("h1", parent=_STYLES["Heading1"], fontName=FONT_NAME, fontSize=14, leading=20, spaceBefore=12, spaceAfter=8)
S_H2 = ParagraphStyle("h2", parent=_STYLES["Heading2"], fontName=FONT_NAME, fontSize=12, leading=17, spaceBefore=9, spaceAfter=6)
S_BODY = ParagraphStyle("b", parent=_STYLES["BodyText"], fontName=FONT_NAME, fontSize=10.5, leading=17, spaceAfter=5)
S_NOTE = ParagraphStyle("n", parent=S_BODY, textColor=colors.HexColor("#555555"), fontSize=9.5)


def _table(data: list[list[str]], widths: list[float] | None = None) -> Table:
    rows = [[Paragraph(str(c), S_BODY) for c in row] for row in data]
    t = Table(rows, colWidths=widths, repeatRows=1)
    t.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#999999")),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF0FF")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    return t


def build_pdf(filename: str, title: str, blocks: list) -> None:
    doc = SimpleDocTemplate(
        str(OUT / filename),
        pagesize=A4,
        title=title,
        leftMargin=20 * mm,
        rightMargin=20 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )
    story = [Paragraph(title, S_TITLE)]
    for kind, payload in blocks:
        if kind == "h1":
            story.append(Paragraph(payload, S_H1))
        elif kind == "h2":
            story.append(Paragraph(payload, S_H2))
        elif kind == "p":
            story.append(Paragraph(payload, S_BODY))
        elif kind == "note":
            story.append(Paragraph(payload, S_NOTE))
        elif kind == "table":
            story.append(_table(payload))
            story.append(Spacer(1, 6))
        elif kind == "pagebreak":
            story.append(PageBreak())
        elif kind == "spacer":
            story.append(Spacer(1, payload))
    doc.build(story)
    print(f"  生成 {filename}")


def build_docx(filename: str, title: str, sections: list[tuple[str, str | list[list[str]]]]) -> None:
    d = Document()
    style = d.styles["Normal"]
    style.font.name = "微软雅黑"
    style.font.size = Pt(10.5)
    d.add_heading(title, level=0)
    for heading, content in sections:
        d.add_heading(heading, level=1)
        if isinstance(content, str):
            for para in content.split("\n"):
                if para.strip():
                    d.add_paragraph(para.strip())
        else:
            table = d.add_table(rows=1, cols=len(content[0]))
            table.style = "Light Grid Accent 1"
            for i, c in enumerate(content[0]):
                table.rows[0].cells[i].text = str(c)
            for row in content[1:]:
                cells = table.add_row().cells
                for i, c in enumerate(row):
                    cells[i].text = str(c)
    d.save(str(OUT / filename))
    print(f"  生成 {filename}")


